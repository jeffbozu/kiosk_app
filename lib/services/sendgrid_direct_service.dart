  static String _buildEmailText({
    required Map<String, dynamic> t,
    required String plate,
    required String zone,
    required String start,
    required String end,
    required String duration,
    required String price,
    required String method,
    String? customMessage,
  }) {
    final lines = <String>[];

    lines.add(t['title']);
    lines.add('');
    lines.add(t['greeting']);
    lines.add('');
    lines.add(t['intro']);
    lines.add('');

    if (customMessage != null) {
      lines.add('Mensaje: $customMessage');
      lines.add('');
    }

    lines.add('Detalles del Ticket:');
    lines.add('${t['plate']}: $plate');
    lines.add('${t['zone']}: $zone');
    lines.add('${t['start']}: $start');
    lines.add('${t['end']}: $end');
    lines.add('${t['duration']}: $duration');
    lines.add('${t['price']}: $price');
    lines.add('${t['method']}: $method');
    lines.add('');
    lines.add(t['thanks']);
    lines.add('');
    lines.add(t['footer']);
    lines.add('© ${DateTime.now().year} Meypark');

    return lines.join('\n');
  }

  static String _detectLocale(String locale) {
    if (locale.startsWith('ca')) return 'ca';
    if (locale.startsWith('en')) return 'en';
    return 'es';
  }

  static String _formatDuration(DateTime start, DateTime end) {
    final d = end.difference(start);
    final hours = d.inHours;
    final minutes = d.inMinutes % 60;

    if (hours > 0) {
      return '${hours}h ${minutes}min';
    }
    return '${minutes}min';
  }

  static String _formatPrice(double price, String locale) {
    final format = NumberFormat.currency(
      locale: locale,
      symbol: '€',
      decimalDigits: 2,
    );
    return format.format(price);
  }

  static String _getMethodName(String method, String locale) {
    final methods = {
      'es': {
        'card': 'Tarjeta',
        'qr': 'QR Pay',
        'mobile': 'Apple/Google Pay',
        'cash': 'Efectivo',
        'bizum': 'Bizum',
      },
      'ca': {
        'card': 'Targeta',
        'qr': 'QR Pay',
        'mobile': 'Apple/Google Pay',
        'cash': 'Efectiu',
        'bizum': 'Bizum',
      },
      'en': {
        'card': 'Card',
        'qr': 'QR Pay',
        'mobile': 'Apple/Google Pay',
        'cash': 'Cash',
        'bizum': 'Bizum',
      },
    };

    return methods[locale]?[method] ?? method;
  }

  static Future<bool> checkSendGridConfig() async {
    try {
      final response = await http
          .get(
            Uri.parse('$_baseUrl/user/profile'),
            headers: {'Authorization': 'Bearer $_apiKey'},
          )
          .timeout(const Duration(seconds: 10));

      if (response.statusCode == 200) {
        print('✅ SendGrid Direct configurado correctamente');
        return true;
      } else {
        print('❌ Error de configuración de SendGrid Direct: ${response.body}');
        return false;
      }
    } catch (e) {
      print('❌ Error conectando con SendGrid Direct: $e');
      return false;
    }
  }

