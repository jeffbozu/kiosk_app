  static Future<bool> sendTicketEmail({
    required String recipientEmail,
    required String plate,
    required String zone,
    required DateTime start,
    required DateTime end,
    required double price,
    required String method,
    String? qrData,
    String? customSubject,
    String? customMessage,
    String locale = 'es',
  }) async {
    try {
      // Detectar idioma
      final lang = _detectLocale(locale);
      final t = _translations[lang] ?? _translations['es']!;

      // Formatear fechas
      final dateFmt = DateFormat('dd/MM/yyyy HH:mm');
      final duration = _formatDuration(start, end);
      final priceFormatted = _formatPrice(price, lang);

      // Crear contenido HTML del email
      final htmlContent = _buildEmailHTML(
        t: t,
        plate: plate,
        zone: zone,
        start: dateFmt.format(start),
        end: dateFmt.format(end),
        duration: duration,
        price: priceFormatted,
        method: _getMethodName(method, lang),
        customMessage: customMessage,
      );

      // Crear contenido de texto plano
      final textContent = _buildEmailText(
        t: t,
        plate: plate,
        zone: zone,
        start: dateFmt.format(start),
        end: dateFmt.format(end),
        duration: duration,
        price: priceFormatted,
        method: _getMethodName(method, lang),
        customMessage: customMessage,
      );

      // Configurar email para SendGrid API
      final emailData = {
        'personalizations': [
          {
            'to': [
              {'email': recipientEmail},
            ],
            'subject': customSubject ?? t['subject'],
          },
        ],
        'from': {'email': 'jbolanos.meypar@gmail.com', 'name': 'Meypark'},
        'content': [
          {'type': 'text/plain', 'value': textContent},
          {'type': 'text/html', 'value': htmlContent},
        ],
      };

      print('📧 SendGrid Direct - Enviando email:');
      print('   Destinatario: $recipientEmail');
      print('   Idioma: $lang');
      print('   Asunto: ${customSubject ?? t['subject']}');

      // Enviar a SendGrid API
      final response = await http
          .post(
            Uri.parse('$_baseUrl/mail/send'),
            headers: {
              'Content-Type': 'application/json',
              'Authorization': 'Bearer $_apiKey',
            },
            body: jsonEncode(emailData),
          )
          .timeout(const Duration(seconds: 30));

      print('📧 SendGrid Direct - Respuesta:');
      print('   Status Code: ${response.statusCode}');
      print('   Body: ${response.body}');

      if (response.statusCode == 202) {
        print('✅ Email enviado exitosamente via SendGrid Direct');
        return true;
      } else {
        print('❌ Error enviando email via SendGrid Direct: ${response.body}');
        return false;
      }
    } catch (e) {
      print('❌ Error en SendGridDirectService: $e');
      return false;
    }
  }

